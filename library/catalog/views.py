from django.shortcuts import render


def book_detail(request):
    # 1. Создаем словарь (контекст) с данными, которые хотим передать в HTML-шаблон.
    # В реальном проекте эти данные вы бы брали из базы данных (модели),
    # но для теста мы просто напишем их вручную.
    context = {
        'book': {
            'title': 'Преступление и наказание',
            'author': 'Федор Достоевский',
            'year': 1866,
            'description': 'Это социально-психологический и философский роман, '
                           'в котором главный герой, бывший студент Родион Раскольников, '
                           'совершает убийство старухи-процентщицы.'
        }
    }

    # 2. Функция render() берет запрос (request), путь к шаблону и контекст (данные).
    # Она "склеивает" HTML-файл с нашими данными и возвращает готовую страницу.
    return render(request, 'catalog/book_detail.html', context)